import {
  existsSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, parse } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(
  root,
  "apps",
  "replay",
  "src",
  "scene",
  "city",
  "buildingCatalog.generated.ts",
);
const scale = 3.25;
const clearance = 0.35;
const tileSize = 2;

const sources = [
  {
    kit: "city-builder",
    objDirectory: join(
      root,
      "assets",
      "3d-models",
      "city-builder",
      "Assets",
      "obj",
    ),
    glbDirectory: join(
      root,
      "assets",
      "3d-models",
      "city-builder",
      "Assets",
      "gltf",
    ),
    include: (name) => /^building_[A-H]_withoutBase\.obj$/i.test(name),
    glbName: (name) => `${parse(name).name}.gltf`,
    publicPath: (name) =>
      `/assets/replay-models/city-builder/gltf/${name}`,
  },
  ...["suburban", "industrial", "commercial"].map((kit) => ({
    kit,
    objDirectory: join(
      root,
      "assets",
      "3d-models",
      `city-kit-${kit}`,
      "Models",
      "OBJ format",
    ),
    glbDirectory: join(
      root,
      "assets",
      "3d-models",
      `city-kit-${kit}`,
      "Models",
      "GLB format",
    ),
    include: (name) =>
      /^(?:building|low-detail-building).+\.obj$/i.test(name),
    glbName: (name) => `${parse(name).name}.glb`,
    publicPath: (name) =>
      `/assets/replay-models/city-kits/${kit}/${name}`,
  })),
];

const specs = [];
for (const source of sources) {
  for (const objName of readdirSync(source.objDirectory)
    .filter(source.include)
    .sort()) {
    const glbName = source.glbName(objName);
    const glbPath = join(source.glbDirectory, glbName);
    if (!existsSync(glbPath)) {
      throw new Error(`Missing building asset: ${glbPath}`);
    }
    const bounds = readObjBounds(join(source.objDirectory, objName));
    const modelId = parse(objName).name;
    const id = `${source.kit}:${modelId}`;
    specs.push({
      id,
      kit: source.kit,
      modelId,
      templateKey: `building:${source.kit}:${modelId}`,
      assetPath: source.publicPath(glbName),
      width: round(bounds.maxX - bounds.minX),
      depth: round(bounds.maxZ - bounds.minZ),
      height: round(bounds.maxY - bounds.minY),
      preferredWidthTiles: preferredTiles(bounds.maxX - bounds.minX),
      preferredDepthTiles: preferredTiles(bounds.maxZ - bounds.minZ),
      heightTier:
        bounds.maxY - bounds.minY < 1.8
          ? "low"
          : bounds.maxY - bounds.minY < 3.2
            ? "mid"
            : "high",
      targetScale: scale,
      modelQuarterTurns: 0,
    });
  }
}

const simplePolyManifestPath = join(
  root,
  "assets",
  "replay-models",
  "simplepoly",
  "catalog.json",
);
if (!existsSync(simplePolyManifestPath)) {
  throw new Error(
    `Missing SimplePoly conversion manifest: ${simplePolyManifestPath}`,
  );
}
const simplePolyManifest = JSON.parse(
  readFileSync(simplePolyManifestPath, "utf8"),
);
for (const building of simplePolyManifest.buildings) {
  const {
    sourcePath: _sourcePath,
    texturePath: _texturePath,
    signature: _signature,
    ...spec
  } = building;
  specs.push(spec);
}
specs.sort((left, right) => left.id.localeCompare(right.id));

const contents = `// Generated by scripts/generate-city-building-catalog.mjs.
import type { BuildingSpec } from "./cityTypes.js";

export const BUILDING_CATALOG = ${JSON.stringify(specs, null, 2)} as const satisfies readonly BuildingSpec[];
`;

writeFileSync(output, contents);
console.log(`Generated ${specs.length} building specifications at ${output}`);

function preferredTiles(size) {
  return Math.max(1, Math.ceil((size * scale + clearance) / tileSize));
}

function round(value) {
  return Number(value.toFixed(4));
}

function readObjBounds(path) {
  let minX = Number.POSITIVE_INFINITY;
  let minY = Number.POSITIVE_INFINITY;
  let minZ = Number.POSITIVE_INFINITY;
  let maxX = Number.NEGATIVE_INFINITY;
  let maxY = Number.NEGATIVE_INFINITY;
  let maxZ = Number.NEGATIVE_INFINITY;
  for (const line of readFileSync(path, "utf8").split(/\r?\n/u)) {
    if (!line.startsWith("v ")) {
      continue;
    }
    const [, xText, yText, zText] = line.trim().split(/\s+/u);
    const x = Number(xText);
    const y = Number(yText);
    const z = Number(zText);
    if (![x, y, z].every(Number.isFinite)) {
      continue;
    }
    minX = Math.min(minX, x);
    minY = Math.min(minY, y);
    minZ = Math.min(minZ, z);
    maxX = Math.max(maxX, x);
    maxY = Math.max(maxY, y);
    maxZ = Math.max(maxZ, z);
  }
  if (![minX, minY, minZ, maxX, maxY, maxZ].every(Number.isFinite)) {
    throw new Error(`No OBJ vertices found in ${path}`);
  }
  return { minX, minY, minZ, maxX, maxY, maxZ };
}
