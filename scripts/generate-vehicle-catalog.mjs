async function createSpec(source) {
  const document = await io.read(source.localPath);
  const scene = document.getRoot().listScenes()[0];
  if (scene === undefined || document.getRoot().listMeshes().length === 0) {
    throw new Error(`Vehicle asset is empty: ${source.localPath}`);
  }
  const bounds = getBounds(scene);
  const xSize = bounds.max[0] - bounds.min[0];
  const ySize = bounds.max[1] - bounds.min[1];
  const zSize = bounds.max[2] - bounds.min[2];
  if (![xSize, ySize, zSize].every((size) => size > 0)) {
    throw new Error(`Vehicle has invalid bounds: ${source.localPath}`);
  }
  const vehicleClass = classifyVehicle(source.modelId);
  const sourceWidth = Math.min(xSize, zSize);
  const sourceLength = Math.max(xSize, zSize);
  const widthScale =
    (laneWidth * targetWidthRatios[vehicleClass]) / sourceWidth;
  const lengthScale = targetLengthCaps[vehicleClass] / sourceLength;
  const targetScale = Math.min(widthScale, lengthScale);
  return {
    ...source,
    localPath: undefined,
    vehicleClass,
    sourceWidth: round(sourceWidth),
    sourceLength: round(sourceLength),
    sourceHeight: round(ySize),
    width: round(sourceWidth * targetScale),
    length: round(sourceLength * targetScale),
    height: round(ySize * targetScale),
    targetScale: round(targetScale),
    modelQuarterTurns: xSize > zSize ? 1 : 0,
    groundOffset: round(Math.max(0, -bounds.min[1] * targetScale)),
  };
}

function isRoadVehicle(fileName) {
  return (
    !/(?:kart|race|tractor|debris|wheel|cone|box)/iu.test(fileName) &&
    /\.glb$/iu.test(fileName)
  );
}

function classifyVehicle(modelId) {
  if (/(?:ambulance|fire|police)/iu.test(modelId)) {
    return "emergency";
  }
  if (/(?:bus|school)/iu.test(modelId)) {
    return "bus";
  }
  if (/(?:truck|container|delivery|garbage|pick.?up)/iu.test(modelId)) {
    return "truck";
  }
  if (/van/iu.test(modelId)) {
    return "van";
  }
  return "passenger";
}

function createDocumentation(catalog) {
  const counts = new Map();
  for (const spec of catalog) {
    counts.set(spec.vehicleClass, (counts.get(spec.vehicleClass) ?? 0) + 1);
  }
  const table = catalog
    .map(
      (spec) =>
        `| \`${spec.id}\` | ${spec.sourceFormat} | ${spec.conversion} | \`${spec.sourcePath}\` | \`${spec.assetPath}\` | \`${spec.textureDependency}\` | ${spec.vehicleClass} | ${spec.sourceWidth.toFixed(3)} × ${spec.sourceLength.toFixed(3)} × ${spec.sourceHeight.toFixed(3)} | ${spec.width.toFixed(3)} × ${spec.length.toFixed(3)} × ${spec.height.toFixed(3)} | ${spec.targetScale.toFixed(4)} | ${spec.modelQuarterTurns} | ${spec.groundOffset.toFixed(4)} |`,
    )
    .join("\n");
  return `# Replay vehicle assets

This file is generated by \`scripts/generate-vehicle-catalog.mjs\`. Do not edit it manually.

## Selection

- Kenney Cars: standalone road vehicles only; karts, race cars, tractors, debris, loose wheels, cones, and boxes are excluded.
- City Builder: every standalone \`car_*.gltf\` asset.
- SimplePoly City and Urban: only models from the separated-wheels directories. Color variants are collapsed to the default, \`Color01\`, or first-numbered texture.

## Excluded resources

- Kenney Cars: \`kart*\`, \`race*\`, \`tractor*\`, \`debris*\`, \`wheel*\`, cones, and boxes. The replay-only \`kart-oobi\` motorcycle proxy is copied for backward compatibility but is not part of this catalog.
- SimplePoly: every Static Wheels duplicate, loose wheel component, alternate color variant, demo scene, and non-land vehicle. Only each model's Separated Wheels version is retained.
- Other packs: buildings, roads, props, rail vehicles, aircraft, boats, construction-only equipment, and full-scene FBX files are outside the road-vehicle catalog.

Total: **${catalog.length} vehicles** (${[...counts.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, count]) => `${name}: ${count}`)
    .join(", ")}).

## Scale and orientation

The replay road uses an approximately ${laneWidth.toFixed(3)}-unit lane width. Each model is measured from its scene-space bounding box and uniformly scaled so its horizontal short side occupies the class ratio below. Final dimensions are stored in world units.

| Class | Lane-width ratio | Target width | Maximum length |
| --- | ---: | ---: | ---: |
${Object.entries(targetWidthRatios)
  .map(
    ([name, ratio]) =>
      `| ${name} | ${(ratio * 100).toFixed(0)}% | ${(ratio * laneWidth).toFixed(3)} | ${targetLengthCaps[name].toFixed(3)} |`,
  )
  .join("\n")}

The uniform scale is \`min(width fit, length fit)\`. \`modelQuarterTurns\` is \`1\` when the source model's long axis is X and \`0\` when it is Z. \`groundOffset\` raises the scaled source minimum Y to zero.

${renderOccupancyMarkdown(catalog).trimEnd()}

## Catalog

| ID | Source format | Conversion | Source | Runtime asset | Texture | Class | Source W × L × H | Final W × L × H | Scale | Quarter turns | Ground offset |
| --- | --- | --- | --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: |
${table}
`;
}

function round(value) {
  return Number(value.toFixed(6));
}
