    sourcePath: (name) =>
      `assets/3d-models/cars/Models/GLB format/${name}`,
    sourceFormat: "GLB",
    conversion: "direct",
    textureDependency:
      "assets/3d-models/cars/Models/GLB format/Textures/colormap.png",
