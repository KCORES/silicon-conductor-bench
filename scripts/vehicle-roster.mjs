import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SIMULATION_SLOT_LENGTH = 1;
const LENGTH_EPSILON = 1e-4;

export function lengthSlotsForWorldLength(length) {
  if (!Number.isFinite(length) || length <= 0) {
    throw new Error(`Vehicle length must be positive: ${length}`);
  }
  return Math.max(
    1,
    Math.ceil((length - LENGTH_EPSILON) / SIMULATION_SLOT_LENGTH),
  );
}

export function rosterFromCatalog(specs) {
  return specs.map((spec) => ({
    id: spec.id,
    vehicleClass: spec.vehicleClass,
    width: spec.width,
    length: spec.length,
    lengthSlots: lengthSlotsForWorldLength(spec.length),
  }));
}

export function renderRosterModule(roster) {
  return `// Generated by scripts/generate-vehicle-catalog.mjs. Do not edit.
// One simulation slot is ${SIMULATION_SLOT_LENGTH} world unit along a vehicle route.
// lengthSlots = max(1, ceil((length - ${LENGTH_EPSILON}) / SIMULATION_SLOT_LENGTH)).

export const SIMULATION_SLOT_LENGTH = ${SIMULATION_SLOT_LENGTH};

export const VEHICLE_ROSTER = ${JSON.stringify(roster, null, 2)} as const;

export type CatalogVehicleId = (typeof VEHICLE_ROSTER)[number]["id"];
export type CatalogVehicleClass =
  (typeof VEHICLE_ROSTER)[number]["vehicleClass"];
`;
}

export function renderOccupancyMarkdown(specs) {
  const rows = rosterFromCatalog(specs)
    .map(
      (vehicle) =>
        `| \`${vehicle.id}\` | ${vehicle.vehicleClass} | ${vehicle.length.toFixed(3)} | ${vehicle.lengthSlots} |`,
    )
    .join("\n");
  return `## Simulation occupancy

The benchmark samples each route in ${SIMULATION_SLOT_LENGTH}-world-unit cells. A vehicle occupies \`lengthSlots = max(1, ceil((length - ${LENGTH_EPSILON}) / ${SIMULATION_SLOT_LENGTH}))\` cells, so the body fits in the grid without spilling into the next cell. Legacy \`SEDAN\` uses \`kenney-cars:sedan\`. Legacy \`MOTORCYCLE\` stays on 1 cell; \`kart-oobi\` is a compatibility proxy and is not in this catalog. Random benchmark demand draws from this roster by class weight. Catalog vehicles use the sedan toll; only \`MOTORCYCLE\` uses the motorcycle toll.

| ID | Class | Length | Slots |
| --- | --- | ---: | ---: |
${rows}
`;
}

export function writeVehicleRoster(specs) {
  const outputPath = join(root, "src", "core", "vehicleRoster.generated.ts");
  writeFileSync(outputPath, renderRosterModule(rosterFromCatalog(specs)));
  return outputPath;
}

export function upsertOccupancySection(markdown, specs) {
  const section = renderOccupancyMarkdown(specs).trimEnd();
  const start = markdown.indexOf("## Simulation occupancy\n");
  const catalog = markdown.indexOf("## Catalog\n");
  if (catalog === -1) {
    throw new Error("Vehicle asset doc is missing the catalog section");
  }
  if (start !== -1 && start < catalog) {
    return `${markdown.slice(0, start)}${section}\n\n${markdown.slice(catalog)}`;
  }
  return `${markdown.slice(0, catalog)}${section}\n\n${markdown.slice(catalog)}`;
}

function readCatalogSpecs() {
  const source = readFileSync(
    join(
      root,
      "apps",
      "replay",
      "src",
      "scene",
      "vehicleCatalog.generated.ts",
    ),
    "utf8",
  );
  const start = source.indexOf("[");
  const end = source.indexOf("] as const");
  if (start === -1 || end === -1) {
    throw new Error("Could not parse the generated vehicle catalog");
  }
  return JSON.parse(source.slice(start, end + 1));
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  const specs = readCatalogSpecs();
  const rosterPath = writeVehicleRoster(specs);
  const docPath = join(root, "docs", "replay-vehicle-assets.md");
  writeFileSync(
    docPath,
    upsertOccupancySection(readFileSync(docPath, "utf8"), specs),
  );
  const slots = rosterFromCatalog(specs).map((vehicle) => vehicle.lengthSlots);
  console.log(
    `Wrote ${specs.length} vehicle roster entries to ${rosterPath} (slots ${Math.min(...slots)}-${Math.max(...slots)})`,
  );
}
